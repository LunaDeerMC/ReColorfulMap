#!/usr/bin/env python3
"""Run the real offline migration CLI against copies of a stopped Paper fixture.

The fixture must have been generated by ColorfulMap 2.3 or the RCME2E Bukkit
plugin on a real Paper server. This runner does not synthesize NBT and never
writes to fixture_root.
It tests process boundaries and crash recovery; storage_oracle.py independently
compares the actual world NBT and images before and after a successful migration.
"""
from __future__ import annotations

import argparse
import contextlib
import fcntl
import hashlib
import json
import os
from pathlib import Path
import shutil
import signal
import struct
import subprocess
import sys
import tempfile
import time


HERE = Path(__file__).resolve().parent
MIGRATE = HERE.parent / "migrate_colorfulmap.py"
ORACLE = HERE / "storage_oracle.py"
TRANSACTIONS = ".recolorfulmap-migrations"


def hash_file(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def census(root):
    """Include bytes/mode/owner of every fixture file, except migration journals."""
    result = {}
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root)
        if relative.parts[0] == TRANSACTIONS or not path.is_file():
            continue
        info = path.stat()
        result[str(relative)] = (hash_file(path), info.st_mode & 0o777, info.st_uid, info.st_gid)
    return result


def worlds(root):
    return sorted(path.parent for path in root.rglob("level.dat")
                  if "plugins" not in path.relative_to(root).parts
                  and TRANSACTIONS not in path.relative_to(root).parts)


@contextlib.contextmanager
def lock_fixture(root):
    handles = []
    try:
        for world in worlds(root):
            handle = (world / "session.lock").open("r+b")
            handles.append(handle)
            fcntl.lockf(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        yield
    finally:
        for handle in handles:
            handle.close()


def snapshot(source, target):
    target.mkdir()
    for world in worlds(source):
        shutil.copytree(world, target / world.relative_to(source), copy_function=shutil.copy2)
    for name in ("ColorfulMap", "ReColorfulMap"):
        directory = source / "plugins" / name
        if directory.exists():
            shutil.copytree(directory, target / "plugins" / name, copy_function=shutil.copy2)
    fixture = source / "plugins/RCME2E/legacy-fixture.json"
    if fixture.is_file():
        destination = target / fixture.relative_to(source)
        destination.parent.mkdir(parents=True)
        shutil.copy2(fixture, destination)


class Suite:
    def __init__(self, fixture, work):
        self.fixture = fixture
        self.work = work
        self.baseline = work / "baseline"
        self.results = []
        self.log_counter = 0
        with lock_fixture(fixture):
            before = census(fixture)
            snapshot(fixture, self.baseline)
            assert census(fixture) == before, "Fixture changed while taking a stopped-server snapshot"
        self.fixture_hashes = before

    def copy(self, name):
        target = self.work / name
        shutil.copytree(self.baseline, target, copy_function=shutil.copy2)
        return target

    def cli(self, root, *args, success=True):
        command = [sys.executable, str(MIGRATE), "--server-root", str(root), *args]
        result = subprocess.run(command, text=True, capture_output=True, timeout=180)
        self.log_counter += 1
        (self.work / f"cli-{self.log_counter:02d}.json").write_text(json.dumps({
            "command": command, "returncode": result.returncode,
            "stdout": result.stdout, "stderr": result.stderr,
        }, indent=2), encoding="utf-8")
        assert (result.returncode == 0) == success, f"Unexpected CLI status: {result.returncode}\n{result.stderr}\n{result.stdout}"
        return json.loads(result.stdout) if success else result

    def oracle(self, before, after, target="plugins/ReColorfulMap"):
        command = [sys.executable, str(ORACLE), "--before", str(before), "--after", str(after), "--target", target]
        result = subprocess.run(command, text=True, capture_output=True, timeout=180)
        assert result.returncode == 0, f"Independent storage oracle failed: {result.stderr}\n{result.stdout}"
        return json.loads(result.stdout)

    def record(self, name, **data):
        result = {"case": name, "passed": True, **data}
        self.results.append(result)
        print(json.dumps(result, ensure_ascii=False), flush=True)

    def unchanged_failure(self, name, mutate, *args):
        root = self.copy(name)
        mutate(root)
        before = census(root)
        result = self.cli(root, "--apply", *args, success=False)
        assert census(root) == before, f"Failed preflight changed fixture files: {name}"
        assert not (root / TRANSACTIONS).exists(), f"Preflight failure entered commit: {name}"
        self.record(name, error=result.stderr.strip())

    def run(self):
        root = self.copy("dry-run")
        before = census(root)
        result = self.cli(root)
        assert result["status"] == "dry_run" and result["migrated"] > 0
        assert census(root) == before and not (root / TRANSACTIONS).exists()
        self.record("dry-run-preserves-actual-paper-files", result=result)

        source_png = next((self.baseline / "plugins/ColorfulMap/maps").glob("*/0_0.png")).relative_to(self.baseline)
        self.unchanged_failure("missing-image", lambda root: (root / source_png).unlink())

        def conflict(root):
            target = root / "plugins/ReColorfulMap/maps" / source_png.parts[-2] / source_png.name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(b"different-existing-target")

        self.unchanged_failure("conflicting-target", conflict)

        def bad_region(root):
            region = next(root.glob("**/region/r.*.*.mca"))
            data = bytearray(region.read_bytes())
            struct.pack_into(">I", data, 0, (2 << 8))  # offset with a zero sector count
            region.write_bytes(data)

        self.unchanged_failure("corrupt-real-region", bad_region)

        def bad_compression(root):
            region = next(root.glob("**/region/r.*.*.mca"))
            data = bytearray(region.read_bytes())
            for offset in range(0, 4096, 4):
                location = struct.unpack_from(">I", data, offset)[0]
                if location:
                    data[(location >> 8) * 4096 + 4] = 4
                    region.write_bytes(data)
                    return
            raise AssertionError("No actual chunk in Paper region fixture")

        self.unchanged_failure("unsupported-region-compression", bad_compression)

        root = self.copy("locked-world")
        before = census(root)
        with lock_fixture(root):
            result = self.cli(root, "--apply", success=False)
        assert census(root) == before
        assert "locked" in result.stderr.lower()
        self.record("separate-process-world-lock", error=result.stderr.strip())

        root = self.copy("successful-roundtrip")
        before = census(root)
        result = self.cli(root, "--apply")
        assert result["status"] == "applied" and result["migrated"] > 0
        manifest = json.loads((Path(result["transaction"]) / "manifest.json").read_text())
        changed_players = [Path(change["path"]).relative_to(root) for change in manifest["changes"]
                           if change["path"].endswith(".dat")
                           and ("/players/data/" in change["path"] or "/playerdata/" in change["path"])]
        assert changed_players, "A real player save containing indexed legacy maps is required"
        self.migrated_player = changed_players[0]
        oracle = self.oracle(self.baseline, root)
        migrated = census(root)
        repeated = self.cli(root, "--apply")
        assert repeated["status"] == "already_migrated" and census(root) == migrated
        rollback = self.cli(root, "--rollback", result["transaction"])
        assert rollback["status"] == "rolled_back" and census(root) == before
        self.record("apply-independent-oracle-repeat-rollback", migration=result, oracle=oracle)

        root = self.copy("in-place-roundtrip")
        before = census(root)
        result = self.cli(root, "--apply", "--target", "plugins/ColorfulMap")
        assert not (root / "plugins/ColorfulMap/maps/maps.yml").exists()
        oracle = self.oracle(self.baseline, root, "plugins/ColorfulMap")
        assert self.cli(root, "--apply", "--target", "plugins/ColorfulMap")["status"] == "already_migrated"
        self.cli(root, "--rollback", result["transaction"])
        assert census(root) == before
        self.record("in-place-index-removal-and-rollback", oracle=oracle)

        root = self.copy("rollback-conflict")
        before = census(root)
        result = self.cli(root, "--apply")
        manifest = json.loads((Path(result["transaction"]) / "manifest.json").read_text())
        save = next(Path(change["path"]) for change in manifest["changes"]
                    if change["before"] and change["path"].endswith(".dat"))
        valid = save.read_bytes()
        save.write_bytes(valid + b"external-edit")
        changed = census(root)
        error = self.cli(root, "--rollback", result["transaction"], success=False)
        assert census(root) == changed
        save.write_bytes(valid)
        self.cli(root, "--rollback", result["transaction"])
        assert census(root) == before
        self.record("rollback-refuses-later-edits", error=error.stderr.strip())

        self.crash_recovery()
        assert census(self.fixture) == self.fixture_hashes, "Original stopped fixture changed during safety tests"
        return {"passed": True, "fixture_root": str(self.fixture), "baseline": str(self.baseline),
                "work_directory": str(self.work), "cases": self.results}

    def crash_recovery(self):
        root = self.copy("process-killed-mid-commit")
        before = census(root)
        probe = self.cli(root)
        assert probe["migrated"] > 0
        player = root / self.migrated_player
        # Select a save actually changed by the successful migration. A fixture
        # server may also contain players whose inventories have no legacy map.
        library = self.work / "rename-pause.so"
        build = subprocess.run(["gcc", "-shared", "-fPIC", "-Wall", "-Wextra", "-o", str(library), str(HERE / "rename_pause.c"), "-ldl"],
                               text=True, capture_output=True, timeout=30)
        assert build.returncode == 0, build.stderr
        marker = self.work / "atomic-rename-paused"
        environment = dict(os.environ, LD_PRELOAD=str(library), RCM_E2E_PAUSE_RENAME=str(player), RCM_E2E_PAUSE_MARKER=str(marker))
        command = [sys.executable, str(MIGRATE), "--server-root", str(root), "--apply"]
        process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, env=environment)
        try:
            deadline = time.monotonic() + 180
            while not marker.exists() and process.poll() is None and time.monotonic() < deadline:
                time.sleep(0.01)
            assert marker.exists(), "Migration did not reach the selected real-player atomic rename"
            process.send_signal(signal.SIGKILL)
            stdout, stderr = process.communicate(timeout=10)
        finally:
            if process.poll() is None:
                process.kill()
                process.communicate(timeout=10)
        assert process.returncode == -signal.SIGKILL
        assert census(root) != before, "Crash injection did not produce a partial commit"
        transactions = sorted((root / TRANSACTIONS).glob("*/manifest.json"))
        assert len(transactions) == 1
        manifest_path = transactions[0]
        assert json.loads(manifest_path.read_text())["state"] == "committing"
        interrupted = census(root)
        error = self.cli(root, "--apply", success=False)
        assert "Interrupted" in error.stderr and census(root) == interrupted
        self.cli(root, "--rollback", str(manifest_path.parent))
        assert census(root) == before, "SIGKILL recovery did not restore original Paper files exactly"
        result = self.cli(root, "--apply")
        oracle = self.oracle(self.baseline, root)
        self.record("sigkill-after-atomic-player-save-rename", killed_returncode=process.returncode,
                    interrupted_error=error.stderr.strip(), recovered_migration=result, oracle=oracle)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture-root", required=True, type=Path)
    parser.add_argument("--work-dir", type=Path)
    args = parser.parse_args()
    fixture = args.fixture_root.resolve()
    if args.work_dir is None:
        work = Path(tempfile.mkdtemp(prefix="recolorfulmap-real-save-safety-"))
    else:
        work = args.work_dir.resolve()
        work.mkdir(parents=True, exist_ok=False)
    try:
        result = Suite(fixture, work).run()
    except BaseException as error:
        result = {"passed": False, "error": str(error), "fixture_root": str(fixture), "work_directory": str(work)}
        (work / "report.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
        raise
    (work / "report.json").write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps({"passed": True, "report": str(work / "report.json"), "cases": len(result["cases"])}))


if __name__ == "__main__":
    main()
